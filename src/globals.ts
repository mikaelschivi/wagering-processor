export const TX_LOCK_TIMEOUT_MS = 2000;
export const TX_STATEMENT_TIMEOUT_MS = 5000;
export const TX_IDLE_IN_TX_TIMEOUT_MS = 15000;
export const USE_CASE_DEADLINE_MS = 10000;
export const SQS_VISIBILITY_TIMEOUT_S = 60;
export const SQS_MAX_RECEIVE_COUNT = 5;
export const SQS_VISIBILITY_SAFETY_MARGIN_S = 20;
export const SQS_RETRY_BACKOFF_CAP_S = 60;
export const SHUTDOWN_DRAIN_MS = 20000;
export const REFERENCE_CLAIM_BATCH = 10;
export const REFERENCE_PROCESS_CONCURRENCY = 5;
export const REFERENCE_CLAIM_LEASE_S = 30;
export const OUTBOX_SQS_REQUEST_TIMEOUT_MS = 3000;
export const OUTBOX_TX_IDLE_TIMEOUT_MS = 10000;
export const USE_CASE_MAX_ATTEMPTS = 5;
export const RETRY_JITTER_MIN_MS = 5;
export const RETRY_JITTER_MAX_MS = 25;
export const REFERENCE_FIRST_ATTEMPT_DELAY_MS = 5000;
export const READY_DB_TIMEOUT_MS = 1000;
export const READY_SQS_TIMEOUT_MS = 2000;
export const DEFAULT_SUPPORTED_CURRENCIES = "BRL,USD";

export interface NestingInput {
  TX_LOCK_TIMEOUT_MS: number;
  TX_STATEMENT_TIMEOUT_MS: number;
  TX_IDLE_IN_TX_TIMEOUT_MS: number;
  USE_CASE_DEADLINE_MS: number;
  SQS_VISIBILITY_TIMEOUT_S: number;
  SQS_VISIBILITY_SAFETY_MARGIN_S: number;
  SQS_RETRY_BACKOFF_CAP_S: number;
  REFERENCE_CLAIM_BATCH: number;
  REFERENCE_PROCESS_CONCURRENCY: number;
  REFERENCE_CLAIM_LEASE_S: number;
  OUTBOX_SQS_REQUEST_TIMEOUT_MS: number;
  OUTBOX_TX_IDLE_TIMEOUT_MS: number;
  SHUTDOWN_DRAIN_MS: number;
}

const STOP_GRACE_PERIOD_MS = 30_000;
const SQS_MAX_VISIBILITY_FACTOR = 12;
const OUTBOX_SEND_MARGIN_MS = 500;

export function nestingViolations(c: NestingInput): string[] {
  const rules: [string, boolean][] = [
    [
      "TX_LOCK_TIMEOUT_MS < TX_STATEMENT_TIMEOUT_MS < TX_IDLE_IN_TX_TIMEOUT_MS",
      c.TX_LOCK_TIMEOUT_MS < c.TX_STATEMENT_TIMEOUT_MS &&
        c.TX_STATEMENT_TIMEOUT_MS < c.TX_IDLE_IN_TX_TIMEOUT_MS,
    ],
    [
      "USE_CASE_DEADLINE_MS + TX_LOCK_TIMEOUT_MS + TX_STATEMENT_TIMEOUT_MS < SQS_VISIBILITY_SAFETY_MARGIN_S",
      c.USE_CASE_DEADLINE_MS + c.TX_LOCK_TIMEOUT_MS + c.TX_STATEMENT_TIMEOUT_MS <
        c.SQS_VISIBILITY_SAFETY_MARGIN_S * 1000,
    ],
    [
      "SQS_VISIBILITY_SAFETY_MARGIN_S < SQS_VISIBILITY_TIMEOUT_S",
      c.SQS_VISIBILITY_SAFETY_MARGIN_S < c.SQS_VISIBILITY_TIMEOUT_S,
    ],
    [
      "ceil(REFERENCE_CLAIM_BATCH / REFERENCE_PROCESS_CONCURRENCY) * USE_CASE_DEADLINE_MS <= REFERENCE_CLAIM_LEASE_S",
      Math.ceil(c.REFERENCE_CLAIM_BATCH / c.REFERENCE_PROCESS_CONCURRENCY) * c.USE_CASE_DEADLINE_MS <=
        c.REFERENCE_CLAIM_LEASE_S * 1000,
    ],
    [
      "OUTBOX_SQS_REQUEST_TIMEOUT_MS + 500 < OUTBOX_TX_IDLE_TIMEOUT_MS",
      c.OUTBOX_SQS_REQUEST_TIMEOUT_MS + OUTBOX_SEND_MARGIN_MS < c.OUTBOX_TX_IDLE_TIMEOUT_MS,
    ],
    ["SHUTDOWN_DRAIN_MS < 30000", c.SHUTDOWN_DRAIN_MS < STOP_GRACE_PERIOD_MS],
    [
      "SQS_RETRY_BACKOFF_CAP_S <= SQS_VISIBILITY_TIMEOUT_S * 12",
      c.SQS_RETRY_BACKOFF_CAP_S <= c.SQS_VISIBILITY_TIMEOUT_S * SQS_MAX_VISIBILITY_FACTOR,
    ],
  ];
  return rules.filter(([, ok]) => !ok).map(([rule]) => rule);
}
